"""Regenerate docs/data-dictionary.md from the models (make docs), so it never drifts."""

from typing import Any

from django.apps import apps
from django.core.management.base import BaseCommand

APP_ORDER = [
    "accounts",
    "locations",
    "catalog",
    "registry",
    "farms",
    "surveys",
    "production",
    "imports",
    "reports",
    "audit",
]
BASE_FIELDS = {
    "id",
    "created_at",
    "updated_at",
    "created_by",
    "updated_by",
    "deleted_at",
    "deleted_by",
}
# Personal data beyond each model's PERSONAL_FIELDS (RA 10173).
EXTRA_PERSONAL = {
    "accounts.user": {"email", "first_name", "last_name", "password"},
    "audit.auditlog": {"ip", "user_agent"},
    "imports.importjob": {"file", "summary", "error_report"},
    "production.harvest": {"buyer"},
}


def _type(field: Any) -> str:
    if field.is_relation and field.related_model is not None:
        kind = "M2M" if field.many_to_many else "FK"
        return f"{kind} → {field.related_model._meta.label_lower}"
    name = field.get_internal_type().replace("Field", "")
    max_length = getattr(field, "max_length", None)
    return f"{name}({max_length})" if max_length and name == "Char" else name


def _notes(field: Any) -> str:
    parts = []
    if getattr(field, "choices", None):
        parts.append("one of: " + ", ".join(str(v) for v, _ in field.choices))
    if field.unique:
        parts.append("unique")
    if field.help_text:
        parts.append(str(field.help_text))
    return "; ".join(parts)


class Command(BaseCommand):
    help = "Print the data dictionary as Markdown."

    def handle(self, *args: Any, **options: Any) -> None:
        out = [
            "# Data dictionary",
            "",
            "Generated by `manage.py data_dictionary` (`make docs`). Do not edit by hand.",
            "",
            "**PII** marks personal data under RA 10173: never in fixtures, logs or git; "
            "masked in the audit log (ADR-0006); hidden from roles without `view_personal_data`.",
            "",
            "Tables built on BaseModel also have: `id` (UUID), "
            "`created_at`, `updated_at`, `created_by`, `updated_by`, `deleted_at`, `deleted_by` "
            "(soft delete; ADR-0006).",
            "",
        ]
        for label in APP_ORDER:
            config = apps.get_app_config(label)
            for model in config.get_models():
                key = model._meta.label_lower
                personal = set(getattr(model, "PERSONAL_FIELDS", ())) | EXTRA_PERSONAL.get(
                    key, set()
                )
                out += [f"## `{model._meta.db_table}` ({key})", ""]
                doc = (model.__doc__ or "").strip().splitlines()[0] if model.__doc__ else ""
                if doc and not doc.startswith(model.__name__ + "("):
                    out += [doc, ""]
                out += ["| Field | Type | Null | PII | Notes |", "|---|---|---|---|---|"]
                for field in model._meta.get_fields():
                    if not getattr(field, "concrete", False) and not field.many_to_many:
                        continue
                    if field.auto_created and not field.concrete:
                        continue
                    if field.name in BASE_FIELDS and key != "audit.auditlog":
                        continue
                    if key == "accounts.user" and field.name in {"groups", "user_permissions"}:
                        continue
                    null = "yes" if getattr(field, "null", False) else ""
                    pii = "**PII**" if field.name in personal else ""
                    out.append(
                        f"| `{field.name}` | {_type(field)} | {null} | {pii} | {_notes(field)} |"
                    )
                constraints = [c.name for c in model._meta.constraints]
                if constraints:
                    out += ["", "Constraints: " + ", ".join(f"`{c}`" for c in constraints)]
                out.append("")
        self.stdout.write("\n".join(out))
